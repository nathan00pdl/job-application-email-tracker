package com.nathanpaiva.jobtracker.adapters.gmail;

import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * The three values needed to read the mailbox.
 *
 * <p>None of them has a default, and each is checked when the application starts. A
 * deployment missing one stops there, naming the variable, instead of starting and then
 * failing on the first call to Google with an authentication error that says nothing
 * useful.
 *
 * <p>They are secrets: they live in environment variables locally and in GitHub Actions
 * secrets in production, and never in this repository. The refresh token is the one that
 * expires — seven days after it was generated, while the OAuth app is in Testing. The
 * access tokens it produces last about an hour and are never stored.
 *
 * @param clientId     identifies this application to Google, not the user
 * @param clientSecret proves the application is the one it claims to be
 * @param refreshToken the credential generated by hand, with the {@code gmail.readonly}
 *                     scope and nothing else
 */
@ConfigurationProperties(prefix = "gmail")
record GmailProperties(String clientId, String clientSecret, String refreshToken) {

    GmailProperties {
        requireSet(clientId, "GMAIL_CLIENT_ID");
        requireSet(clientSecret, "GMAIL_CLIENT_SECRET");
        requireSet(refreshToken, "GMAIL_REFRESH_TOKEN");
    }

    /**
     * Refuses a setting that was never given a value.
     *
     * <p>Spring does not do this on its own. A {@code ${GMAIL_CLIENT_ID}} with no such
     * variable is not an error to it: the property keeps that text, placeholder and all.
     * And GitHub Actions hands a missing secret over as an empty string. Either way the
     * application would start, and only fail later against the service, far from the
     * cause.
     *
     * <p>The message names the variable and never repeats the value: the run's log is
     * public, and a value that is half right is still a secret.
     */
    private static void requireSet(String value, String variable) {
        if (value == null || value.isBlank() || value.startsWith("${")) {
            throw new IllegalArgumentException(variable + " is not set");
        }
    }
}
